export const DEFAULT_THEME_ID = "navy-sky";

export function getTheme(id) {
  return COLOR_THEMES.find((t) => t.id === id) ?? COLOR_THEMES[0];
}

/**
 * Resolves a theme's CSS-variable RGB triplets ("R G B") into `rgb(r, g, b)` strings keyed by
 * shade, e.g. `getThemeColors(id).primary["600"]`. For color props that can't be plain CSS
 * (recharts fills/strokes, inline SVG in the world map and progress rings) — anywhere a literal
 * color string is required instead of a Tailwind class, pull from here instead of hardcoding
 * hex, so those elements repaint too when the palette switcher changes theme.
 */
export function getThemeColors(id) {
  const theme = getTheme(id);
  const toRgb = (triplet) => `rgb(${triplet.replaceAll(" ", ", ")})`;
  const primary = {};
  const accent = {};
  for (const [key, value] of Object.entries(theme.vars)) {
    if (key.startsWith("--color-primary-")) primary[key.replace("--color-primary-", "")] = toRgb(value);
    if (key.startsWith("--color-accent-")) accent[key.replace("--color-accent-", "")] = toRgb(value);
  }
  primary.DEFAULT = toRgb(theme.vars["--color-primary"]);
  accent.DEFAULT = toRgb(theme.vars["--color-accent"]);
  return { primary, accent };
}
